#!/usr/bin/env python3
"""Turn finished entries in terms/*.po into the files Odoo actually reads.

Only entries that are translated and NOT fuzzy are built.

  model / model_terms strings (menus, field labels, view text, selection values)
      -> zh_tw_overrides/i18n/zh_TW.po   (an installable add-on; its manifest
         depends on the overridden modules so it loads after them)

  code strings (Python and JavaScript: buttons, dialogs, error messages)
      -> code_overlays/<module>/i18n_extra/zh_TW.po
         Odoo only reads code translations from the module's own folder, so these
         are bind-mounted into the container (see docker-compose.snippet.yml).

Usage:  python3 scripts/build.py
"""
import glob
import os
import shutil
import sys

import polib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import LANG, is_translated, copy_entry, new_po  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADDON = os.path.join(ROOT, "zh_tw_overrides")
OVERLAYS = os.path.join(ROOT, "code_overlays")
# Path of the addons inside the official odoo Docker image (verify with the
# command in the README if you use another image).
IMAGE_ADDONS = "/usr/lib/python3/dist-packages/odoo/addons"

MANIFEST = '''# Generated by scripts/build.py - edit terms/*.po, not this file.
{{
    "name": "zh_TW translation overrides",
    "summary": "Company wording for Traditional Chinese, kept outside Odoo core",
    "version": "20.0.1.0.0",
    "license": "LGPL-3",
    "category": "Hidden",
    "depends": {depends},
    "data": [],
    "installable": True,
    "auto_install": False,
}}
'''


def main():
    model_po = new_po()
    code_pos = {}
    model_modules = set()
    counts = {}

    for path in sorted(glob.glob(os.path.join(ROOT, "terms", "*.po"))):
        mod = os.path.splitext(os.path.basename(path))[0]
        n_model = n_code = 0
        for e in polib.pofile(path, wrapwidth=0):
            if not is_translated(e):
                continue
            model_occ = [o for o in e.occurrences if not o[0].startswith("code:")]
            code_occ = [o for o in e.occurrences if o[0].startswith("code:")]
            if model_occ:
                model_po.append(copy_entry(e, occurrences=model_occ, flags=[]))
                for occ, _ in model_occ:
                    # model:ir.ui.menu,name:stock.menu_x -> stock
                    model_modules.add(occ.split(":")[-1].split(".")[0])
                n_model += 1
            if code_occ:
                code_pos.setdefault(mod, new_po()).append(copy_entry(e, occurrences=code_occ, flags=[]))
                n_code += 1
        counts[mod] = (n_model, n_code)

    # add-on with database-side overrides
    os.makedirs(os.path.join(ADDON, "i18n"), exist_ok=True)
    model_po.save(os.path.join(ADDON, "i18n", f"{LANG}.po"))
    depends = sorted(model_modules | {"base"})
    with open(os.path.join(ADDON, "__manifest__.py"), "w", encoding="utf-8") as f:
        f.write(MANIFEST.format(depends=repr(depends)))
    open(os.path.join(ADDON, "__init__.py"), "a").close()

    # code overlays, one folder per module that has code overrides
    if os.path.isdir(OVERLAYS):
        shutil.rmtree(OVERLAYS)
    os.makedirs(OVERLAYS)
    open(os.path.join(OVERLAYS, ".gitkeep"), "w").close()
    mounts = []
    for mod, po in sorted(code_pos.items()):
        d = os.path.join(OVERLAYS, mod, "i18n_extra")
        os.makedirs(d)
        po.save(os.path.join(d, f"{LANG}.po"))
        mounts.append(f"      - ./odoo-zh-tw/code_overlays/{mod}/i18n_extra:{IMAGE_ADDONS}/{mod}/i18n_extra:ro")

    with open(os.path.join(ROOT, "docker-compose.snippet.yml"), "w", encoding="utf-8") as f:
        f.write("# Generated by scripts/build.py. Merge these lines into the volumes of the\n"
                "# `web` service in your docker-compose.yml, then recreate the container.\n"
                "services:\n  web:\n    volumes:\n"
                "      - ./odoo-zh-tw:/mnt/zh-tw-addons:ro   # add /mnt/zh-tw-addons to addons_path\n")
        f.write("\n".join(mounts) + ("\n" if mounts else ""))

    for mod, (a, b) in counts.items():
        if a or b:
            print(f"{mod:18} database strings: {a:5}   code strings: {b:5}")
    print(f"add-on depends on: {', '.join(depends)}")
    print(f"code overlays for: {', '.join(sorted(code_pos)) or '(none yet)'}")


if __name__ == "__main__":
    main()
